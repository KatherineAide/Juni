const ALL_CHECKS: CheckId[] = [
  "physical_address",
  "payment_methods",
  "refund_policy",
  "independent_reviews",
  "visa_claims",
  "registration",
  "price_crosscheck",
];

function record(
  status: VerificationRecord["status"],
  lastChecked: string,
  sources: Source[],
  overrides: Partial<Record<CheckId, { result: CheckResult; note: L }>> = {},
): VerificationRecord {
  const checks: VerificationCheck[] = ALL_CHECKS.map((id) => {
    const o = overrides[id];
    return o ? { id, ...o } : { id, result: "pass", note: passNotes[id] };
  });
  return { status, lastChecked, sources, checks };
}

